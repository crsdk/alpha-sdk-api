// Emit the spec's PropertyName enum as a runtime array.
//
// openapi-typescript produces types only, but we want the closed slug list at
// runtime so an unknown property can be rejected with a useful message instead
// of a bare 400 from the camera server. Reads the generated schema so the list
// can never drift from the types.
import { readFileSync, writeFileSync } from "node:fs";

const SCHEMA = "src/api/schema.d.ts";
const OUT = "src/api/property-names.ts";

const source = readFileSync(SCHEMA, "utf8");
const match = source.match(/^\s*PropertyName:\s*(.+);$/m);
if (!match) {
  console.error(`Could not find the PropertyName union in ${SCHEMA}. Run codegen first.`);
  process.exit(1);
}

const names = [...match[1].matchAll(/"([^"]+)"/g)].map((m) => m[1]);
if (names.length === 0) {
  console.error("PropertyName union parsed to an empty list — refusing to write.");
  process.exit(1);
}

writeFileSync(
  OUT,
  `// GENERATED by scripts/gen-property-names.mjs — do not edit.
// Source: ../api/openapi.yaml -> components.schemas.PropertyName
import type { PropertyName } from "./client.js";

export const PROPERTY_NAMES: readonly PropertyName[] = [
${names.map((n) => `  "${n}",`).join("\n")}
];

const KNOWN = new Set<string>(PROPERTY_NAMES);

/** True if the slug is one the spec declares. */
export function isPropertyName(name: string): name is PropertyName {
  return KNOWN.has(name);
}
`,
);

console.log(`✨ ${OUT} — ${names.length} property names`);
